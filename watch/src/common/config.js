// Адрес шлюза и токен устройства сюда не вписываются
// (см. также docs/architecture.md — куда переезжает шлюз и при чём тут телефон).: их генерирует
// `npm run setup` в server/ и кладёт в config.local.js, который в .gitignore.
// Так боевой токен не попадает в историю репозитория и не расходится с тем,
// что записано в server/.env.
//
// Если config.local.js ещё не создан, `npm run build` в watch/ создаёт пустую
// заглушку, сборка проходит, а приложение на часах показывает баннер
// «Шлюз ещё не настроен».
import { LOCAL } from "./config.local"

export var GATEWAY_URL = LOCAL.gatewayUrl || ""
export var DEVICE_TOKEN = LOCAL.deviceToken || ""
// Метка сборки. Настройки живут в @system.storage и переживают переустановку
// .rpk, поэтому без метки часы продолжали бы стучаться по адресу прошлой
// установки, сколько бы раз ни пересобирали приложение. При смене метки
// адрес и токен берутся из новой сборки.
export var CONFIG_STAMP = LOCAL.stamp || ""
export var MAX_RECORDING_MS = 10000
// Озвучивать ответы вслух. По умолчанию выключено: часы не должны заговорить
// в людном месте без явного разрешения.
// Озвучка ответов включена по умолчанию: часы без экрана перед глазами —
// это прежде всего голос, а выключенная озвучка выглядит ровно как сломанная.
// Раньше стояло false, и «звука нет» отчасти означало именно это.
export var SPEAK_ANSWERS = true
// "auto" — провайдер выбирает шлюз (как настроено в .env);
// "gemini" или "openai" — явный выбор с часов.
export var AI_PROVIDER = "auto"
// Сколько ждать ответа системного модуля, прежде чем считать, что он молчит.
// Обычный запрос к шлюзу — быстрый; отправка записи и синтез речи дольше.
// Способ доставки записи по умолчанию. "bytes" — чтение файла и отправка
// сырых байтов; в эмуляторе работает именно он, а request.upload молчит.
export var TRANSFER_MODE = "bytes"
// Канал через телефон (Bluetooth) заметно медленнее Wi-Fi: рукопожатие TLS
// и первый запрос могут занять секунды. Прежние пределы обрывали связь
// раньше, чем она успевала установиться, и это выглядело как «шлюз
// недоступен», хотя адрес открывается с того же телефона в браузере.
export var REQUEST_TIMEOUT_MS = 30000
// Отправка записи по Bluetooth — это десятки килобайт на узком канале,
// плюс распознавание и ответ модели на шлюзе.
export var UPLOAD_TIMEOUT_MS = 60000
// Запись: длительность плюс запас на то, чтобы рантайм закрыл файл.
export var RECORD_TIMEOUT_MS = 18000
